// Renders $...$ and $$...$$ (written via pymdownx.arithmatex) with KaTeX, on the first
// page load and after every instant-navigation page change.
document$.subscribe(({ body }) => {
  renderMathInElement(body, {
    delimiters: [
      { left: "$$", right: "$$", display: true },
      { left: "$", right: "$", display: false },
      { left: "\\(", right: "\\)", display: false },
      { left: "\\[", right: "\\]", display: true },
    ],
  });
});
